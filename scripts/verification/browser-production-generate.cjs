const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
async function run() {
  assert.equal(process.platform, 'win32')
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: true })
  const root = path.join(process.env.LOCALAPPDATA, 'VoiceStudio', 'data')
  const before = new Set(await fs.readdir(path.join(root, 'outputs')))
  const evidence = await fs.mkdtemp(path.join(os.tmpdir(), 'voice-production-generate-'))
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    await context.grantPermissions(['local-network-access'], { origin: 'https://recording-voice-web.vercel.app' })
    const page = await context.newPage()
    await page.goto('https://recording-voice-web.vercel.app')
    await page.getByRole('heading', { name: '스튜디오', exact: true }).waitFor()
    await page.getByRole('navigation', { name: '주 메뉴' }).getByRole('button', { name: '음성 만들기', exact: true }).click()
    const existingWork = page.getByRole('option', { name: '표현 음성 샘플' })
    if (await existingWork.count()) await page.getByRole('combobox', { name: '저장한 작업' }).selectOption({ label: '표현 음성 샘플' })
    await page.getByLabel('제목', { exact: true }).fill('표현 음성 샘플')
    await page.getByRole('textbox', { name: '읽을 텍스트' }).fill('안녕하세요. 오늘은 제 목소리로 새로운 문장을 읽어보겠습니다.')
    await page.getByRole('combobox', { name: '음성 엔진' }).selectOption('chatterbox-multilingual-v2')
    await page.getByRole('slider', { name: '표현 강도' }).fill('0.8')
    const button = page.getByRole('group', { name: '생성 동작' }).getByRole('button', { name: '음성 만들기', exact: true })
    assert.equal(await button.isDisabled(), false, 'Generation unavailable in production UI')
    await button.click()
    await page.getByText('음성을 만들었어요.', { exact: true }).waitFor({ timeout: 900000 })
    await page.getByRole('region', { name: '생성 이력' }).getByRole('button', { name: '듣기', exact: true }).first().click()
    await page.waitForFunction(() => [...document.querySelectorAll('.generation-history audio')].some((audio) => audio.currentTime > 0), { timeout: 30000 })
    const after = await fs.readdir(path.join(root, 'outputs'))
    const created = after.filter((name) => !before.has(name) && name.endsWith('.json'))
    assert.equal(created.length, 1)
    const result = JSON.parse(await fs.readFile(path.join(root, 'outputs', created[0]), 'utf8'))
    assert.equal(result.model_id, 'chatterbox-multilingual-v2')
    assert.equal(result.expression_intensity, 0.8)
    await page.screenshot({ path: path.join(evidence, 'generated.png'), fullPage: true })
    const report = { status: 'passed', url: 'https://recording-voice-web.vercel.app', result_id: result.id, duration_seconds: result.duration_seconds, model_id: result.model_id, expression_intensity: result.expression_intensity, evidence, listening_accepted: false }
    await fs.writeFile(path.join(evidence, 'evidence.json'), JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report, null, 2))
  } finally { await browser.close() }
}
run().catch((error) => { console.error(error); process.exitCode = 1 })
